// Port of validators/email.validator.ts. The regex is unanchored, exactly as in Angular.
import { toRule, type ValidationErrors, type ValidationRule } from './types';

export const EMAIL_ERROR_MESSAGE = 'Invalid email format.';

const emailRegex =
	/(?:[a-z0-9!#$%&'*+/=?^_`{|}~-]+(?:\.[a-z0-9!#$%&'*+/=?^_`{|}~-]+)*|"(?:[\x01-\x08\x0b\x0c\x0e-\x1f\x21\x23-\x5b\x5d-\x7f]|\\[\x01-\x09\x0b\x0c\x0e-\x7f])*")@(?:(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z0-9](?:[a-z0-9-]*[a-z0-9])?|\[(?:(?:(2(5[0-5]|[0-4][0-9])|1[0-9][0-9]|[1-9]?[0-9]))\.){3}(?:(2(5[0-5]|[0-4][0-9])|1[0-9][0-9]|[1-9]?[0-9])|[a-z0-9-]*[a-z0-9]:(?:[\x01-\x08\x0b\x0c\x0e-\x1f\x21-\x5a\x53-\x7f]|\\[\x01-\x09\x0b\x0c\x0e-\x7f])+)\])/;

/** `{ isInvalidEmail: true }` for a non-empty value that doesn't contain an email, otherwise `null`. */
export function emailErrors(value: unknown): ValidationErrors | null {
	if (value && !emailRegex.test(String(value))) return { isInvalidEmail: true };
	return null;
}

export function emailValidation(): ValidationRule {
	return toRule(emailErrors, () => EMAIL_ERROR_MESSAGE);
}
